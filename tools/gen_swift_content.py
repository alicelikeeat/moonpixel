#!/usr/bin/env python3
"""Generates ios/Sources/MoonPixelCore/ContentData.swift from content/*.json.
The JSON files stay the single source of truth for tiles and biomes."""
import json, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
tiles = json.load(open(os.path.join(root, "content/tiles/tiles.json")))["tiles"]
biomes = json.load(open(os.path.join(root, "content/biomes/biomes.json")))["biomes"]

def s(v): return json.dumps(v, ensure_ascii=False)
def col(a, i):
    return s(a[i]) if len(a) > i and isinstance(a[i], str) and a[i].startswith("#") else '""'

out = ["// GENERATED by tools/gen_swift_content.py from content/*.json. Do not edit.", "", "enum ContentData {", "    static let tiles: [TileDef] = ["]
for t in tiles:
    a = t["art"]
    stage = a[3] if len(a) > 3 and isinstance(a[3], int) else 0
    grow = t.get("grow")
    harvest_to = t.get("harvest", {}).get("to", "")
    out.append("        TileDef(id: %d, key: %s, layer: %d, solid: %s, water: %s, bridge: %s, natural: %s, big: %s, built: %s, walk: %s, light: %d, growTo: %s, growTime: %s, after: %s, artKind: %s, c1: %s, c2: %s, c3: %s, stage: %d, nameEn: %s, nameZh: %s)," % (
        t["id"], s(t["key"]), t["layer"], "true" if t.get("solid") else "false", "true" if t.get("water") else "false",
        "true" if t.get("bridge") else "false", "true" if t.get("natural") else "false", "true" if t.get("big") else "false",
        "true" if t.get("built") else "false", t.get("walk", 1.0), t.get("light", 0), s(grow["to"] if grow else ""),
        float(grow["time"]) if grow else 0.0, s(t.get("after", "")), s(a[0]), col(a, 1), col(a, 2), col(a, 3), stage,
        s(t["name"]["en"]), s(t["name"]["zh"])))
out += ["    ]", "", "    static let biomes: [BiomeDef] = ["]
def pairs(lst): return "[" + ", ".join("(%s, %s)" % (s(e[0]), float(e[1])) for e in lst) + "]"
for b in biomes:
    alt = b.get("alt", ["", 0.0])
    out.append("        BiomeDef(index: %d, key: %s, group: %s, color: %s, ground: %s, alt: %s, altChance: %s, trees: %s, treeDensity: %s, objects: %s, decor: %s, nameEn: %s, nameZh: %s)," % (
        b["index"], s(b["key"]), s(b["group"]), s(b["color"]), s(b["ground"]), s(alt[0]), float(alt[1]), pairs(b.get("trees", [])),
        float(b.get("tree_density", 0.0)), pairs(b.get("objects", [])), pairs(b.get("decor", [])), s(b["name"]["en"]), s(b["name"]["zh"])))
out += ["    ]", "}", ""]
open(os.path.join(root, "ios/Sources/MoonPixelCore/ContentData.swift"), "w").write("\n".join(out))
print("tiles", len(tiles), "biomes", len(biomes))
